# S1_VAR_02

x = 10
print(f"Value: {x}, Type: {type(x).__name__}")

x = "hello"
print(f"Value: {x}, Type: {type(x).__name__}")

x = [1, 2, 3]
print(f"Value: {x}, Type: {type(x).__name__}")

x = 3.14
print(f"Value: {x}, Type: {type(x).__name__}")

# comment: dynamic typing means we can change the type of data a variable holds at runtime